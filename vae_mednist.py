# ================================
# ANALYSE 2 : Posterior Collapse
# Vérifier si certaines dimensions latentes sont inutilisées
# ================================
print("\n2️⃣ Détection du Posterior Collapse...")
print("   (Si KL ≈ 0 pour une dimension → dimension inactive = collapse)")

# Calculer la KL par dimension sur tout le dataset de test
kl_par_dim = np.zeros(LATENT_DIM)
n_images   = 0

with torch.no_grad():
    for images, _ in test_loader:
        images = images.to(DEVICE)
        mu, log_var = vae.encodeur(images)

        # KL analytique par dimension : -0.5 * (1 + log_var - mu² - exp(log_var))
        kl_dim = -0.5 * (1 + log_var - mu.pow(2) - log_var.exp())
        # Moyenne sur le batch
        kl_par_dim += kl_dim.mean(0).cpu().numpy()
        n_images += 1

kl_par_dim /= n_images

# Seuil : dimension inactive si KL < 0.1
seuil_collapse = 0.1
dims_inactives = np.sum(kl_par_dim < seuil_collapse)

fig, ax = plt.subplots(figsize=(14, 5))
ax.bar(range(LATENT_DIM), sorted(kl_par_dim, reverse=True),
       color=['red' if k < seuil_collapse else 'steelblue'
              for k in sorted(kl_par_dim, reverse=True)],
       alpha=0.8)
ax.axhline(y=seuil_collapse, color='red', linestyle='--', linewidth=1.5,
           label=f'Seuil de collapse ({seuil_collapse})')
ax.set_title('KL par Dimension Latente (triée décroissante)\n'
             'Rouge = dimension inactive (posterior collapse)', fontsize=12)
ax.set_xlabel('Dimension latente (triée par importance)')
ax.set_ylabel('KL moyenne')
ax.legend()
ax.grid(True, alpha=0.3, axis='y')

plt.tight_layout()
plt.savefig('/content/12_posterior_collapse.png', dpi=100, bbox_inches='tight')
plt.show()

print(f"\n📊 Résultats du diagnostic :")
print(f"   Dimensions actives : {LATENT_DIM - dims_inactives}/{LATENT_DIM}")
print(f"   Dimensions inactives (collapse) : {dims_inactives}/{LATENT_DIM}")
print(f"   KL moyenne : {kl_par_dim.mean():.2f}")
print(f"   KL max : {kl_par_dim.max():.2f}")

if dims_inactives > LATENT_DIM // 2:
    print("   ⚠️ Posterior collapse sévère détecté !")
    print("   Suggestion : réduire la dimension latente ou augmenter beta")
elif dims_inactives > LATENT_DIM // 4:
    print("   ⚠️ Posterior collapse partiel détecté.")
    print("   Suggestion : ajuster le taux d'apprentissage ou le warmup KL")
else:
    print("   ✅ Pas de posterior collapse significatif !")

