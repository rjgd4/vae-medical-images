    for images, _ in barre:
        # Déplacer les images sur le bon appareil (GPU ou CPU)
        images = images.to(DEVICE)

        # --- Remise à zéro des gradients ---
        # IMPORTANT : les gradients s'accumulent par défaut dans PyTorch
        # Il faut les remettre à zéro avant chaque batch
        optimizer.zero_grad()

        # --- Passe avant (forward) ---
        # Calculer la reconstruction et les paramètres latents
        x_reconstruit, mu, log_var = vae(images)

        # --- Calculer la perte ---
        perte, recon, kl = vae.calculer_perte(images, x_reconstruit, mu, log_var)

        # --- Passe arrière (backward) ---
        # Calculer les gradients par rapport à tous les paramètres
        perte.backward()

        # Éviter les gradients trop grands (clipping)
        # Cela stabilise l'entraînement
        torch.nn.utils.clip_grad_norm_(vae.parameters(), max_norm=1.0)

        # --- Mise à jour des poids ---
        optimizer.step()

        # Accumuler les pertes
        cumul_perte += perte.item()
        cumul_recon += recon.item()
        cumul_kl    += kl.item()

        # Mettre à jour la barre de progression
        barre.set_postfix({'Loss': f'{perte.item():.1f}',
                           'Recon': f'{recon.item():.1f}',
                           'KL': f'{kl.item():.1f}'})

    # Calculer les moyennes sur l'époque
    n_batchs = len(train_loader)
    perte_moy_train = cumul_perte / n_batchs
    recon_moy       = cumul_recon / n_batchs
    kl_moy          = cumul_kl    / n_batchs

    historique['train_loss'].append(perte_moy_train)
    historique['train_recon'].append(recon_moy)
    historique['train_kl'].append(kl_moy)

    # ========================
    # PHASE D'ÉVALUATION
    # ========================
    vae.eval()  # Mode évaluation (désactive Dropout, etc.)

