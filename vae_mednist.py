def estimer_vraisemblance(vae, images, n_samples=50, device=DEVICE):
    """
    Estime la log-vraisemblance de chaque image par échantillonnage Monte Carlo.

    Principe : pour chaque image x,
    1. Encoder x → obtenir mu et log_var
    2. Échantillonner K vecteurs z_k ~ q(z|x)
    3. Reconstruire chaque z_k → x_k_reconstruit
    4. Estimer log p(x) ≈ log mean_k p(x | z_k)

    Un score élevé = image probable sous le modèle = image "normale"
    Un score bas = image inhabituelle ou aberrante (anomalie)
    """
    vae.eval()
    log_vraisemblances = []

    with torch.no_grad():
        for img in images:
            img = img.unsqueeze(0).to(device)  # Ajouter dimension batch

            # Encoder l'image
            mu, log_var = vae.encodeur(img)
            sigma = torch.exp(0.5 * log_var)

            scores = []
            for _ in range(n_samples):
                # Échantillonner z ~ q(z|x)
                epsilon = torch.randn_like(sigma)
                z = mu + sigma * epsilon

                # Reconstruire l'image depuis z
                img_rec = vae.decodeur(z)

                # Calculer log p(x|z) = -BCE(x_rec, x)
                # (BCE est la perte qui correspond à une distribution de Bernoulli)
                log_p_x_given_z = -F.binary_cross_entropy(
                    img_rec, img, reduction='sum'
                ).item()

                scores.append(log_p_x_given_z)

            # Estimer log p(x) ≈ mean des scores (approximation simple)
            log_vraisemblances.append(np.mean(scores))

    return np.array(log_vraisemblances)


