class Encodeur(nn.Module):
    """
    L'encodeur compresse une image 64x64 en un espace latent de LATENT_DIM dimensions.
    Il produit deux sorties : mu (moyenne) et log_var (log de la variance).

    Architecture :
    Image (1x64x64)
      → Conv(32) + BatchNorm + LeakyReLU  → (32x32x32)
      → Conv(64) + BatchNorm + LeakyReLU  → (64x16x16)
      → Conv(128) + BatchNorm + LeakyReLU → (128x8x8)
      → Conv(256) + BatchNorm + LeakyReLU → (256x4x4)
      → Flatten                            → (4096)
      → Linear → mu et log_var             → (LATENT_DIM) chacun
    """
    def __init__(self, latent_dim):
        super(Encodeur, self).__init__()

        # Bloc convolutif = Conv + BatchNorm + Activation
        # Conv2d(in_channels, out_channels, kernel_size, stride, padding)
        # stride=2 → divise la résolution spatiale par 2 à chaque couche
        self.conv_layers = nn.Sequential(
            # Couche 1 : 1 canal → 32 canaux, 64x64 → 32x32
            nn.Conv2d(1, 32, kernel_size=4, stride=2, padding=1),
            nn.BatchNorm2d(32),       # Normalise les activations par batch
            nn.LeakyReLU(0.2),        # Activation avec légère pente négative

            # Couche 2 : 32 → 64 canaux, 32x32 → 16x16
            nn.Conv2d(32, 64, kernel_size=4, stride=2, padding=1),
            nn.BatchNorm2d(64),
            nn.LeakyReLU(0.2),

            # Couche 3 : 64 → 128 canaux, 16x16 → 8x8
            nn.Conv2d(64, 128, kernel_size=4, stride=2, padding=1),
            nn.BatchNorm2d(128),
            nn.LeakyReLU(0.2),

            # Couche 4 : 128 → 256 canaux, 8x8 → 4x4
            nn.Conv2d(128, 256, kernel_size=4, stride=2, padding=1),
            nn.BatchNorm2d(256),
            nn.LeakyReLU(0.2),
        )

        # Taille de la sortie aplatie : 256 canaux × 4 × 4 = 4096
        self.flatten_size = 256 * 4 * 4

        # Couche linéaire → mu (moyenne de la distribution latente)
        self.fc_mu = nn.Linear(self.flatten_size, latent_dim)

        # Couche linéaire → log_var (log de la variance)
        # On utilise le log de la variance pour la stabilité numérique
        # (la variance doit être positive ; le log peut être n'importe quel réel)
        self.fc_log_var = nn.Linear(self.flatten_size, latent_dim)

    def forward(self, x):
        """
        Passe avant de l'encodeur.
        x : tenseur d'images de forme (batch_size, 1, 64, 64)
        Retourne : mu et log_var de forme (batch_size, latent_dim)
        """
        # Passer à travers les couches convolutives
        x = self.conv_layers(x)  # (batch, 256, 4, 4)

        # Aplatir : transformer le tenseur 3D en vecteur 1D
        # -1 = déduire automatiquement la taille du batch
        x = x.view(-1, self.flatten_size)  # (batch, 4096)

        # Calculer la moyenne et le log de la variance
        mu      = self.fc_mu(x)       # (batch, latent_dim)
        log_var = self.fc_log_var(x)  # (batch, latent_dim)

        return mu, log_var


class Decodeur(nn.Module):
    """
    Le décodeur reconstruit une image 64x64 à partir d'un vecteur latent.

    Architecture (symétrique à l'encodeur) :
    Vecteur latent (LATENT_DIM)
      → Linear                              → (4096)
      → Reshape                             → (256x4x4)
      → ConvTranspose(128) + BN + ReLU      → (128x8x8)
      → ConvTranspose(64) + BN + ReLU       → (64x16x16)
      → ConvTranspose(32) + BN + ReLU       → (32x32x32)
      → ConvTranspose(1) + Sigmoid          → (1x64x64)
    """
    def __init__(self, latent_dim):
        super(Decodeur, self).__init__()

        # Couche linéaire : du vecteur latent vers un tenseur 3D
        self.fc = nn.Linear(latent_dim, 256 * 4 * 4)

        # Couches de convolution transposées ("déconvolutions")
        # ConvTranspose2d est l'inverse de Conv2d : augmente la résolution
        self.deconv_layers = nn.Sequential(
            # Couche 1 : 256 → 128 canaux, 4x4 → 8x8
            nn.ConvTranspose2d(256, 128, kernel_size=4, stride=2, padding=1),
            nn.BatchNorm2d(128),
            nn.ReLU(),           # ReLU standard pour le décodeur

            # Couche 2 : 128 → 64 canaux, 8x8 → 16x16
            nn.ConvTranspose2d(128, 64, kernel_size=4, stride=2, padding=1),
            nn.BatchNorm2d(64),
            nn.ReLU(),

            # Couche 3 : 64 → 32 canaux, 16x16 → 32x32
            nn.ConvTranspose2d(64, 32, kernel_size=4, stride=2, padding=1),
            nn.BatchNorm2d(32),
            nn.ReLU(),

            # Couche 4 : 32 → 1 canal, 32x32 → 64x64
            nn.ConvTranspose2d(32, 1, kernel_size=4, stride=2, padding=1),
            # Sigmoid : force la sortie entre [0, 1]
            # Cohérent avec nos images normalisées entre [0, 1]
            nn.Sigmoid()
        )

    def forward(self, z):
        """
        Passe avant du décodeur.
        z : vecteur latent de forme (batch_size, latent_dim)
        Retourne : images reconstruites de forme (batch_size, 1, 64, 64)
        """
        # Passer par la couche linéaire
        x = self.fc(z)              # (batch, 4096)

        # Reformer en tenseur 4D (batch, canaux, hauteur, largeur)
        x = x.view(-1, 256, 4, 4)  # (batch, 256, 4, 4)

        # Passer par les couches de déconvolution
        x = self.deconv_layers(x)  # (batch, 1, 64, 64)

        return x


class VAE(nn.Module):
    """
    Le modèle VAE complet = Encodeur + Décodeur + astuce de réparamétrage.

    Paramètre beta : permet de contrôler l'importance de la régularisation KL.
    - beta = 1 → VAE standard
    - beta > 1 → β-VAE (favorise le désentrelacement)
    """
    def __init__(self, latent_dim=LATENT_DIM, beta=1.0):
        super(VAE, self).__init__()

        self.latent_dim = latent_dim
        self.beta = beta  # Facteur de pondération du terme KL

        # Instancier l'encodeur et le décodeur
        self.encodeur = Encodeur(latent_dim)
        self.decodeur = Decodeur(latent_dim)

    def reparametriser(self, mu, log_var):
        """
        Astuce de réparamétrisation :
        Au lieu d'échantillonner z directement (ce qui bloquerait les gradients),
        on écrit : z = mu + sigma * epsilon
        où epsilon ~ N(0, I) est aléatoire mais indépendant des paramètres.

        Cela permet de propager les gradients à travers l'opération d'échantillonnage !
        """
        if self.training:
            # Calculer sigma = exp(0.5 * log_var)
            # (on utilise 0.5 * log_var car log_var = log(sigma²) → sigma = exp(log_var/2))
            sigma = torch.exp(0.5 * log_var)

            # Tirer epsilon depuis une loi normale standard
            # epsilon a la même forme que mu et sigma
            epsilon = torch.randn_like(sigma)  # ~ N(0, I)

            # z = mu + sigma * epsilon
            return mu + sigma * epsilon
        else:
            # En mode évaluation (pas d'entraînement), on utilise juste la moyenne
            return mu

    def forward(self, x):
        """
        Passe avant complète du VAE.
        1. Encoder l'image → obtenir mu et log_var
        2. Réparamétrer → obtenir z
        3. Décoder z → obtenir la reconstruction
        """
        # Étape 1 : Encoder
        mu, log_var = self.encodeur(x)

        # Étape 2 : Échantillonner z avec l'astuce de réparamétrage
        z = self.reparametriser(mu, log_var)

        # Étape 3 : Reconstruire l'image
        x_reconstruit = self.decodeur(z)

        return x_reconstruit, mu, log_var

    def calculer_perte(self, x, x_reconstruit, mu, log_var):
        """
        Calcule la perte ELBO = Perte de reconstruction + beta * Divergence KL

        - Perte de reconstruction : à quel point l'image reconstruite
          ressemble-t-elle à l'originale ?
          On utilise BCE (Binary Cross-Entropy) car les pixels sont entre [0,1]

        - Divergence KL : à quel point la distribution latente
          s'écarte-t-elle de la loi normale standard N(0,I) ?
          Formule analytique : KL = -0.5 * sum(1 + log_var - mu² - exp(log_var))
        """
        # --- Perte de reconstruction ---
        # F.binary_cross_entropy : compare pixel à pixel
        # reduction='sum' : somme sur tous les pixels et tous les exemples du batch
        perte_recon = F.binary_cross_entropy(
            x_reconstruit, x, reduction='sum'
        )

        # --- Divergence KL ---
        # Formule exacte pour KL(N(mu, sigma²) || N(0,I))
        # = -0.5 * sum(1 + log(sigma²) - mu² - sigma²)
        kl_div = -0.5 * torch.sum(1 + log_var - mu.pow(2) - log_var.exp())

        # --- Perte totale ELBO ---
        # beta = 1 → VAE classique
        # beta > 1 → β-VAE (pousse davantage vers N(0,I) → désentrelacement)
        perte_totale = perte_recon + self.beta * kl_div

        # Normaliser par la taille du batch pour avoir des valeurs comparables
        batch_size = x.size(0)

        return (perte_totale / batch_size,
                perte_recon / batch_size,
                kl_div / batch_size)


