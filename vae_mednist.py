def interpoler_latent(vae, img1, img2, n_steps=10, device=DEVICE):
    """
    Génère une interpolation entre deux images dans l'espace latent.

    Paramètres :
    - vae     : le modèle VAE entraîné
    - img1    : première image (tenseur)
    - img2    : deuxième image (tenseur)
    - n_steps : nombre de pas d'interpolation
    - device  : CPU ou GPU

    Retourne : liste d'images interpolées
    """
    vae.eval()

    with torch.no_grad():
        # Encoder les deux images → obtenir leurs vecteurs moyens (mu)
        # unsqueeze(0) : ajouter une dimension batch (1, 1, 64, 64)
        mu1, _ = vae.encodeur(img1.unsqueeze(0).to(device))
        mu2, _ = vae.encodeur(img2.unsqueeze(0).to(device))

        images_interpolees = []

        # Générer n_steps vecteurs intermédiaires
        for i, alpha in enumerate(np.linspace(0, 1, n_steps)):
            # Interpolation linéaire : z_alpha = (1-alpha)*z1 + alpha*z2
            # Quand alpha=0 → on est en z1, quand alpha=1 → on est en z2
            z_alpha = (1 - alpha) * mu1 + alpha * mu2

            # Décoder ce vecteur intermédiaire → obtenir une image
            img_generee = vae.decodeur(z_alpha)
            images_interpolees.append(img_generee.cpu().squeeze())

    return images_interpolees


